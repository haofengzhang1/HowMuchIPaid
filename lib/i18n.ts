export const messages = { en, zh };
export type MessageKey = keyof typeof en;

export function t(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
) {
  let value: string = messages[locale][key] ?? messages.en[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

const categoryKeys: Record<string, MessageKey> = {
  Food: "categoryFood",
  Snack: "categorySnack",
  "Home supply": "categoryHomeSupply",
  Transport: "categoryTransport",
  Housing: "categoryHousing",
  Utilities: "categoryUtilities",
  Entertainment: "categoryEntertainment",
  Shopping: "categoryShopping",
  Health: "categoryHealth",
  Other: "categoryOther",
};

export function categoryLabel(locale: Locale, category: string) {
  const key = categoryKeys[category];
  return key ? t(locale, key) : category;
}

